// Keep learning content styles inside their workspace so the original campus shell stays intact.
import {readFileSync, writeFileSync} from 'node:fs';
function scope(source) {
    const css = source.replace(/\/\*[\s\S]*?\*\//g, '');
    let result = '', cursor = 0;
    while (cursor < css.length) {
        const open = css.indexOf('{', cursor);
        if (open < 0) break;
        const selector = css.slice(cursor, open).trim();
        let depth = 1, quote = '', end = open + 1;
        for (; end < css.length && depth; end++) {
            const character = css[end];
            if (quote) { if (character === '\\') end++; else if (character === quote) quote = ''; }
            else if (character === '"' || character === "'") quote = character;
            else if (character === '{') depth++;
            else if (character === '}') depth--;
        }
        const body = css.slice(open + 1, end - 1);
        if (selector.startsWith('@')) result += `${selector}{${scope(body)}}\n`;
        else result += selector.split(',').map(value => value.trim() === ':root' || value.trim() === 'body' ? '.learning-workspace' : `.learning-workspace ${value.trim()}`).join(',') + `{${body}}\n`;
        cursor = end;
    }
    return '/* Generated by scripts/build-campus-theme.mjs. */\n' + result;
}
for (const [source,target] of [['learning.css','campus-learning.css'],['learning-admin.css','campus-admin-content.css']]) {
    writeFileSync(new URL(`../public/css/${target}`, import.meta.url),scope(readFileSync(new URL(`../public/css/${source}`, import.meta.url),'utf8')));
}
